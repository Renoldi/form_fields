/// Keyed collection of one kind of map shape (polygon, polyline, circle or
/// marker) with a cached list view for `flutter_map` layers.
///
/// Every mutation follows the same order: check the controller guard, change
/// the map, refresh the cached list, then notify. [FormFieldsMapNotifier] uses
/// one store per shape kind, so the add/update/remove/clear rules live here
/// once instead of being repeated for each kind.
///
/// Internal to the package. It is not exported from the package barrel.
class MapShapeStore<T> {
  MapShapeStore({
    required this.idPrefix,
    required this._ensureControlled,
    required this._onChanged,
    Map<String, T>? initial,
  }) : _map = initial ?? <String, T>{} {
    _refreshCache();
  }

  /// Prefix used for ids generated by [add], such as `p` for polygons.
  final String idPrefix;

  final void Function() _ensureControlled;
  final void Function() _onChanged;

  Map<String, T> _map;
  List<T> _cache = const [];

  /// Cached list view, in insertion order.
  List<T> get items => _cache;

  /// Mutable view used by bulk raw-marker updates in the notifier. Callers
  /// must call [rebuildCache] after changing it.
  Map<String, T> get raw => _map;

  /// Rebuilds [items] from the current map without notifying.
  void rebuildCache() => _refreshCache();

  /// Read-only view of the stored entries.
  Map<String, T> get unmodifiableMap => Map.unmodifiable(_map);

  /// Returns the value stored under [id], or `null`.
  T? get(String id) => _map[id];

  /// Stores [value] under a new generated id and returns that id.
  String add(T value) {
    _ensureControlled();
    final id = '$idPrefix\$${DateTime.now().microsecondsSinceEpoch}';
    _map[id] = value;
    _commit();
    return id;
  }

  /// Stores [value] under [id], replacing any existing value.
  void addOrUpdate(String id, T value) {
    _ensureControlled();
    _map[id] = value;
    _commit();
  }

  /// Removes [id]. Returns `true` when an entry was removed.
  bool remove(String id) {
    _ensureControlled();
    final removed = _map.remove(id) != null;
    if (removed) _commit();
    return removed;
  }

  /// Removes every entry.
  void clear() {
    _ensureControlled();
    _map.clear();
    _commit();
  }

  /// Replaces all entries with [items]. Each item is stored under
  /// `keyFor(index)`.
  ///
  /// Pass [requireController] as `false` only where the existing public API
  /// allowed the replacement without an attached controller.
  void replaceAll(
    List<T> items,
    String Function(int index) keyFor, {
    bool requireController = true,
  }) {
    if (requireController) _ensureControlled();
    _map = <String, T>{};
    for (var i = 0; i < items.length; i++) {
      _map[keyFor(i)] = items[i];
    }
    _commit();
  }

  /// Loads [items] without checking the controller and without notifying.
  /// Used only while the owning notifier is being constructed.
  void seed(List<T> items, String Function(int index) keyFor) {
    for (var i = 0; i < items.length; i++) {
      _map[keyFor(i)] = items[i];
    }
    _refreshCache();
  }

  void _commit() {
    _refreshCache();
    _onChanged();
  }

  void _refreshCache() {
    _cache = _map.values.toList(growable: false);
  }
}

final _mapLog = Logger('FormFieldsMapNotifier');

/// Owns the raw marker list behind [FormFieldsMapNotifier.rawMarkers] and the
/// bulk algorithms that keep the polygon, polyline, circle, and marker stores
/// in sync with it.
///
/// Every mutation first checks the controller guard and then notifies, exactly
/// as [FormFieldsMapNotifier] did before the split. Internal to the package.
class MapRawMarkerStore {
  MapRawMarkerStore({
    required this.polygons,
    required this.polylines,
    required this.circles,
    required this.markers,
    required this.ensureControlled,
    required this.onChanged,
  });

  final MapShapeStore<Polygon> polygons;
  final MapShapeStore<Polyline> polylines;
  final MapShapeStore<CircleMarker> circles;
  final MapShapeStore<Marker> markers;
  final void Function() ensureControlled;
  final void Function() onChanged;

  // Growable and owned by this store. Appends extend it in place, so a batch
  // costs O(batch) instead of copying the whole list on every call.
  List<dynamic> _rawMarkersCache = <dynamic>[];
  int _rawRevision = 0;

  /// Changes whenever the raw list or one of its entries changes. Widgets use
  /// it to decide when to rebuild, because the list object itself is reused.
  int get rawRevision => _rawRevision;

  void _ensureControlled() => ensureControlled();

  void _scheduleNotify() => onChanged();

  List<dynamic> get rawMarkers => _rawMarkersCache;

  set rawMarkers(List<dynamic> coords) {
    _ensureControlled();
    _rawMarkersCache = List<dynamic>.of(coords);
    _rawRevision++;
    _scheduleNotify();
  }

  /// Append raw markers. When [createMarkerWidgets] is false, the notifier
  /// will skip constructing `Marker` widget entries in `markers.raw` which
  /// is significantly faster for very large point sets when rendering is
  /// done via a canvas painter rather than per-marker widgets.
  void appendRawMarkers(
    List<dynamic> coords, {
    bool createMarkerWidgets = true,
  }) {
    _ensureControlled();
    // Fast path: update the raw cache once, and register all ShapeMeta
    // entries into the concrete layer maps in batch to avoid repeated
    // full-map->list conversions on each single addition (which causes
    // O(n^2) behavior when appending many markers).
    _rawMarkersCache.addAll(coords);
    _rawRevision++;

    try {
      // Collect into the internal maps directly and update caches once.
      for (final r in coords) {
        if (r is ShapeMeta && r.shapeType != null) {
          final type = r.shapeType!.toLowerCase();
          final pms = r.pointMetas;
          if (type == ShapeTypes.polygon && pms != null && pms.isNotEmpty) {
            final pts = pms.map((pm) => pm.point).toList(growable: false);
            final opts = r.polygonOptions();
            final poly = Polygon(
              points: pts,
              color: opts.fillColor ?? Colors.transparent,
              borderColor: opts.borderColor ?? Colors.transparent,
              borderStrokeWidth: opts.borderStrokeWidth ?? 1.0,
            );
            final id = r.id ?? 'p\$${DateTime.now().microsecondsSinceEpoch}';
            r.id ??= id;
            polygons.raw[id] = poly;
          } else if (type == ShapeTypes.polyline &&
              pms != null &&
              pms.isNotEmpty) {
            final pts = pms.map((pm) => pm.point).toList(growable: false);
            final opts = r.polylineOptions();
            final pl = Polyline(
              points: pts,
              strokeWidth: opts.strokeWidth ?? 2.0,
              color: opts.color ?? Colors.transparent,
              useStrokeWidthInMeter: opts.useStrokeWidthInMeter ?? true,
            );
            final rid = r.id ?? 'l\$${DateTime.now().microsecondsSinceEpoch}';
            r.id ??= rid;
            polylines.raw[rid] = pl;
          } else if (type == ShapeTypes.circle &&
              pms != null &&
              pms.isNotEmpty) {
            final center = pms.first.point;
            final rad = pms.first.rotation ?? 10.0;
            final opts = r.circleOptions();
            final c = CircleMarker(
              point: center,
              color: opts.borderColor ?? Colors.transparent,
              borderStrokeWidth: opts.borderStrokeWidth ?? 0.0,
              borderColor: opts.borderColor ?? Colors.transparent,
              useRadiusInMeter: opts.useRadiusInMeter ?? true,
              radius: opts.radiusMeters ?? rad,
            );
            final id = r.id ?? 'c\$${DateTime.now().microsecondsSinceEpoch}';
            r.id ??= id;
            circles.raw[id] = c;
          } else if (type == ShapeTypes.marker &&
              pms != null &&
              pms.isNotEmpty) {
            final center = pms.first.point;
            final opts = r.markerOptions();
            final marker = Marker(
              point: center,
              width: opts.width?.toDouble() ?? 40,
              height: opts.height?.toDouble() ?? 40,
              child: const SizedBox.shrink(),
            );
            final id = r.id ?? 'm\$${DateTime.now().microsecondsSinceEpoch}';
            r.id ??= id;
            if (createMarkerWidgets) {
              markers.raw[id] = marker;
            }
          }
        }
      }

      // Rebuild caches once after the batch mutation.
      polygons.rebuildCache();
      polylines.rebuildCache();
      circles.rebuildCache();
      if (createMarkerWidgets) {
        markers.rebuildCache();
      } else {
        // Keep previous _markersCache to avoid invalidating marker widgets
        // when the caller chooses canvas-only rendering.
      }
    } catch (e, st) {
      _mapLog.fine('Ignored map update error', e, st);
    }

    _scheduleNotify();
  }

  void clearRawMarkers() {
    _ensureControlled();
    _rawMarkersCache = <dynamic>[];
    _rawRevision++;
    _scheduleNotify();
  }

  /// Signals that entries were changed in place (for example coordinates of
  /// `PointMeta` updated by the caller). Rebuilds listeners without copying.
  void touchRawMarkers() {
    _ensureControlled();
    _rawRevision++;
    _scheduleNotify();
  }

  bool removeRawMarker(String id) {
    _ensureControlled();
    final before = _rawMarkersCache.length;
    _rawMarkersCache = _rawMarkersCache.where((m) {
      if (m is ShapeMeta) return m.id != id;
      if (m is Map) return m['id'] != id;
      return true;
    }).toList();
    final removed = _rawMarkersCache.length != before;
    if (removed) {
      _rawRevision++;
      _scheduleNotify();
    }
    return removed;
  }
}
